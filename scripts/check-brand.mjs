// Brand check (CLAUDE.md 8.2): no emojis and no hex colour codes outside
// src/styles/tokens.css.
//
// Older code still contains some of both. Their counts per file are recorded in
// scripts/brand-baseline.mjs; the check fails as soon as a file has MORE than its
// recorded count (or a new file has any). When code is cleaned up, run
//   npm run check:brand -- --update
// to lower the recorded counts. The goal is an empty baseline.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import baseline from "./brand-baseline.mjs";

const ROOT = new URL("..", import.meta.url).pathname;
const SCAN_DIR = join(ROOT, "src");
const ALLOWED_FILE = "src/styles/tokens.css";
const EXTENSIONS = [".ts", ".tsx", ".css", ".js", ".mjs"];

const EMOJI = /\p{Extended_Pictographic}/gu;
// Symbols that are Extended_Pictographic but are not emojis
const NOT_EMOJI = new Set(["©", "®", "™"]);
const HEX = /#[0-9a-fA-F]{3,8}\b/g;

function listFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return listFiles(path);
    return EXTENSIONS.some((ext) => entry.name.endsWith(ext)) ? [path] : [];
  });
}

function countViolations(text) {
  const emojis = (text.match(EMOJI) ?? []).filter((c) => !NOT_EMOJI.has(c));
  const hex = text.match(HEX) ?? [];
  return { emojis: emojis.length, hex: hex.length };
}

const current = {};
for (const path of listFiles(SCAN_DIR)) {
  const file = relative(ROOT, path);
  if (file === ALLOWED_FILE) continue;
  const counts = countViolations(readFileSync(path, "utf8"));
  if (counts.emojis || counts.hex) current[file] = counts;
}

if (process.argv.includes("--update")) {
  const sorted = Object.fromEntries(Object.entries(current).sort());
  writeFileSync(
    new URL("./brand-baseline.mjs", import.meta.url),
    "// Generated by scripts/check-brand.mjs --update. Counts may only go down.\n" +
      `export default ${JSON.stringify(sorted, null, 2)};\n`,
  );
  console.log(
    `Baseline updated: ${Object.keys(sorted).length} files with old violations.`,
  );
  process.exit(0);
}

const problems = [];
for (const [file, counts] of Object.entries(current)) {
  const allowed = baseline[file] ?? { emojis: 0, hex: 0 };
  if (counts.emojis > allowed.emojis)
    problems.push(
      `${file}: ${counts.emojis} emojis (allowed ${allowed.emojis})`,
    );
  if (counts.hex > allowed.hex)
    problems.push(
      `${file}: ${counts.hex} hex colour codes (allowed ${allowed.hex})`,
    );
}

if (problems.length) {
  console.error("Brand check failed. Use tokens and Lucide icons instead:");
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}

const total = Object.values(current).reduce(
  (sum, c) => sum + c.emojis + c.hex,
  0,
);
console.log(`Brand check passed (${total} old violations left to clean up).`);
